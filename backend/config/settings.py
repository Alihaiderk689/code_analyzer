# Supabase's pgbouncer (transaction-mode pooler on port 6543) doesn't support
# server-side cursors; dj_database_url just drops the ?pgbouncer=true flag into
# OPTIONS, where psycopg2 would choke on it, so translate it into the real setting.
if DATABASES['default'].get('OPTIONS', {}).pop('pgbouncer', False):
    DATABASES['default']['DISABLE_SERVER_SIDE_CURSORS'] = True


